"""Generate MANY fresh AI voices: 6 MMS-TTS voices x 4 utterances each.

24 clips, varied prosody (statement/question/excited/narrative).
Guaranteed unseen (MMS not in any training set). Saved as clean .wav.
~2-3 segs per clip -> ~60 AI segments for the final training round.
"""
import torch
import soundfile as sf
from transformers import VitsModel, AutoTokenizer

OUT = r"C:\Users\Kishore GK\Downloads"
LANGS = ['eng', 'fra', 'deu', 'spa', 'ita', 'por']
TEXTS = {
    'eng': ["The weather today is quite pleasant for a walk in the park.",
            "Are you really sure that voice was generated by a machine?",
            "Wow, I can hardly believe how natural this sounds now!",
            "In eighteen twenty seven, the first photograph was taken in France."],
    'fra': ["Il fait beau aujourd hui, sortons nous promener un peu.",
            "Es tu vraiment certain que cette voix est artificielle ?",
            "Incroyable, on dirait une vraie personne qui parle !",
            "Paris est la capitale de la France depuis des siecles."],
    'deu': ["Das Wetter ist heute wirklich sehr angenehm und mild.",
            "Bist du dir sicher, dass diese Stimme kuenstlich ist?",
            "Unglaublich, wie echt diese Stimme doch klingt!",
            "Berlin ist die Hauptstadt von Deutschland seit langer Zeit."],
    'spa': ["Hoy hace un dia estupendo para salir a caminar.",
            "Estas seguro de que esta voz fue generada por una maquina?",
            "Increible, parece una persona real hablando ahora mismo!",
            "Madrid es una ciudad hermosa con mucha historia y cultura."],
    'ita': ["Oggi e una bella giornata per fare una passeggiata.",
            "Sei sicuro che questa voce sia stata generata?",
            "Incredibile, sembra proprio una persona vera!",
            "Roma e una citta antica piena di storia e bellezza."],
    'por': ["Hoje esta um dia otimo para passear no parque.",
            "Voce tem certeza de que esta voz e artificial?",
            "Incrivel, parece uma pessoa de verdade falando!",
            "Lisboa e uma cidade linda cheia de historia."],
}

for li, lang in enumerate(LANGS, 1):
    ckpt = f'facebook/mms-tts-{lang}'
    print(f'loading {ckpt}...', flush=True)
    model = VitsModel.from_pretrained(ckpt)
    tok = AutoTokenizer.from_pretrained(ckpt)
    for ui, text in enumerate(TEXTS[lang], 1):
        with torch.no_grad():
            wav = model(**tok(text, return_tensors='pt')).waveform[0].numpy()
        fn = f'{OUT}\\ai_gen_{lang}_{ui}.wav'
        sf.write(fn, wav, 16000)
        print(f'saved ai_gen_{lang}_{ui}.wav ({len(wav)/16000:.1f}s)', flush=True)
print('ALL 24 AI CLIPS GENERATED')
